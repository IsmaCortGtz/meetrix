func (h *Hub) handleMediaStateChanged(client *Client, payloadBytes []byte) {
	var payload MediaStateChangedPayload
	if err := json.Unmarshal(payloadBytes, &payload); err != nil {
		return
	}

	rm, p := h.getRoomAndParticipant(client)
	if rm == nil || p == nil {
		return
	}

	if payload.AudioMuted != nil {
		p.SetAudioMuted(*payload.AudioMuted)
	}
	if payload.VideoMuted != nil {
		p.SetVideoMuted(*payload.VideoMuted)
	}
	if payload.ScreenSharing != nil {
		p.SetScreenSharing(*payload.ScreenSharing)
	}
	if payload.ScreenTrackID != "" {
		p.SetScreenTrackID(payload.ScreenTrackID)
	} else if payload.ScreenSharing != nil && !*payload.ScreenSharing {
		p.SetScreenTrackID("")
	}

	payload.PeerID = client.peerID
	if payload.ScreenTrackID == "" && p.GetScreenTrackID() != "" {
		payload.ScreenTrackID = p.GetScreenTrackID()
	}
	msg, _ := EncodeMessage(TypeMediaStateChanged, payload)
	rm.Broadcast(msg, client.peerID)
}

func (h *Hub) handleLeave(client *Client) {
	h.Unregister(client)
	_ = client.Close()
}

func (h *Hub) sendError(client *Client, code, message string) {
	errMsg, _ := EncodeMessage(TypeError, ErrorPayload{
		Code:    code,
		Message: message,
	})
	_ = client.Send(errMsg)
}

func (h *Hub) getParticipant(client *Client) *room.Participant {
	if client.roomID == "" || client.peerID == "" {
		return nil
	}
	r, ok := h.roomManager.GetRoom(client.roomID)
	if !ok {
		return nil
	}
	p, _ := r.GetAnyParticipant(client.peerID)
	return p
}

func (h *Hub) getRoomAndParticipant(client *Client) (*room.Room, *room.Participant) {
	if client.roomID == "" || client.peerID == "" {
		return nil, nil
	}
	r, ok := h.roomManager.GetRoom(client.roomID)
	if !ok {
		return nil, nil
	}
	p, _ := r.GetParticipant(client.peerID)
	return r, p
}

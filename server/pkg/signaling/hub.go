var upgrader = websocket.Upgrader{
	CheckOrigin: func(r *http.Request) bool {
		return true // Permissive for local development and SDK clients
	},
	ReadBufferSize:  1024 * 1024,
	WriteBufferSize: 1024 * 1024,
}

// Hub coordinates WebSocket connections, room states, WebRTC signaling, and permissions.
type Hub struct {
	mu          sync.RWMutex
	roomManager *room.RoomManager
	sfuEngine   *sfu.Engine
	auth        auth.Authenticator
	clients     map[*Client]bool
}

// NewHub creates a new signaling Hub.
func NewHub(rm *room.RoomManager, sfuEngine *sfu.Engine, auth auth.Authenticator) *Hub {
	return &Hub{
		roomManager: rm,
		sfuEngine:   sfuEngine,
		auth:        auth,
		clients:     make(map[*Client]bool),
	}
}

// ServeWS handles incoming HTTP requests and upgrades them to WebSocket.
func (h *Hub) ServeWS(w http.ResponseWriter, r *http.Request) {
	conn, err := upgrader.Upgrade(w, r, nil)
	if err != nil {
		return
	}

	client := NewClient(h, conn)

	h.mu.Lock()
	h.clients[client] = true
	h.mu.Unlock()

	go client.WritePump()
	go client.ReadPump()
}

// Unregister disconnects a client and updates the corresponding room.
func (h *Hub) Unregister(client *Client) {
	h.mu.Lock()
	delete(h.clients, client)
	h.mu.Unlock()

	if client.roomID == "" || client.peerID == "" {
		return
	}

	rm, ok := h.roomManager.GetRoom(client.roomID)
	if !ok {
		return
	}

	p, _ := rm.RemoveParticipant(client.peerID)
	if p != nil {
		p.Close()

		leftMsg, _ := EncodeMessage(TypePeerLeft, PeerLeftPayload{
			PeerID: client.peerID,
		})
		rm.Broadcast(leftMsg)
	}
}

// HandleMessage parses and routes signaling messages from clients.
func (h *Hub) HandleMessage(client *Client, msgBytes []byte) {
	var env Envelope
	if err := json.Unmarshal(msgBytes, &env); err != nil {
		h.sendError(client, "INVALID_FORMAT", "Failed to parse message envelope")
		return
	}

	switch env.Type {
	case TypeJoin:
		h.handleJoin(client, env.Payload)
	case TypeOffer:
		h.handleOffer(client, env.Payload)
	case TypeAnswer:
		h.handleAnswer(client, env.Payload)
	case TypeCandidate:
		h.handleCandidate(client, env.Payload)
	case TypeChatMessage:
		h.handleChatMessage(client, env.Payload)
	case TypeReaction:
		h.handleReaction(client, env.Payload)
	case TypeRaiseHand:
		h.handleRaiseHand(client, env.Payload)
	case TypeAdmitPeer:
		h.handleAdmitPeer(client, env.Payload)
	case TypeMutePeer:
		h.handleMutePeer(client, env.Payload)
	case TypeStopPeerMedia:
		h.handleStopPeerMedia(client, env.Payload)
	case TypeKickPeer:
		h.handleKickPeer(client, env.Payload)
	case TypeUpdatePolicies:
		h.handleUpdatePolicies(client, env.Payload)
	case TypeMediaStateChanged:
		h.handleMediaStateChanged(client, env.Payload)
	case TypeLeave:
		h.handleLeave(client)
	default:
		h.sendError(client, "UNKNOWN_TYPE", fmt.Sprintf("Unsupported event type %q", env.Type))
	}
}

func (h *Hub) handleJoin(client *Client, payloadBytes []byte) {
	if client.peerID != "" {
		h.sendError(client, "ALREADY_JOINED", "Client has already joined a room")
		return
	}

	var payload JoinPayload
	if err := json.Unmarshal(payloadBytes, &payload); err != nil {
		h.sendError(client, "INVALID_PAYLOAD", "Invalid join payload")
		return
	}

	if payload.RoomID == "" {
		h.sendError(client, "MISSING_ROOM_ID", "Room ID is required")
		return
	}

	authResp, err := h.auth.Authenticate(context.Background(), auth.AuthRequest{
		RoomID:      payload.RoomID,
		Token:       payload.Token,
		UserID:      payload.UserID,
		DisplayName: payload.DisplayName,
		Metadata:    payload.Metadata,
	})
	if err != nil || authResp == nil || !authResp.Allowed {
		reason := "Authentication failed"
		if authResp != nil && authResp.Reason != "" {
			reason = authResp.Reason
		}
		h.sendError(client, "UNAUTHORIZED", reason)
		_ = client.Close()
		return
	}

	r, err := h.roomManager.GetOrCreateRoom(payload.RoomID)
	if err != nil {
		h.sendError(client, "ROOM_ERROR", err.Error())
		return
	}

	if authResp.RoomPolicy != nil {
		r.UpdatePolicy(*authResp.RoomPolicy)
	}

	peerID := uuid.New().String()
	client.peerID = peerID
	client.roomID = payload.RoomID

	sfuPeer, err := sfu.NewPeer(peerID, payload.RoomID, h.sfuEngine)
	if err != nil {
		h.sendError(client, "SFU_ERROR", fmt.Sprintf("Failed to initialize WebRTC peer: %v", err))
		return
	}

	// Forward trickle ICE candidates generated by Pion to the client
	sfuPeer.OnICECandidate(func(c *webrtc.ICECandidate) {
		if c == nil {
			return
		}
		candidateJSON := c.ToJSON()
		candMsg, _ := EncodeMessage(TypeCandidate, CandidatePayload{
			Candidate:        candidateJSON.Candidate,
			SDPMid:           candidateJSON.SDPMid,
			SDPMLineIndex:    candidateJSON.SDPMLineIndex,
			UsernameFragment: candidateJSON.UsernameFragment,
		})
		_ = client.Send(candMsg)
	})

	// When a participant publishes a new track, distribute to peers in the room
	var partRef *room.Participant
	sfuPeer.SetOnTrackPublished(func(pubTrack *sfu.PublishedTrack) {
		if partRef != nil {
			r.HandleTrackPublished(partRef, pubTrack)
		}
	})

	sfuPeer.SetOnTrackUnpublished(func(trackID string) {
		if partRef != nil {
			r.HandleTrackUnpublished(partRef, trackID)
		}
	})

	// On renegotiation needed from SFU
	sfuPeer.SetOnRenegotiationNeeded(func() {
		offer, err := sfuPeer.CreateOffer()
		if err == nil {
			for _, l := range strings.Split(offer.SDP, "\n") {
				if strings.HasPrefix(l, "m=") || strings.HasPrefix(l, "a=msid") || strings.HasPrefix(l, "a=mid") || strings.HasPrefix(l, "a=sendonly") || strings.HasPrefix(l, "a=inactive") || strings.HasPrefix(l, "a=recvonly") || strings.HasPrefix(l, "a=sendrecv") {
					log.Printf("DBG %s offer: %s", peerID[:4], strings.TrimSpace(l))
				}
			}
			offerMsg, _ := EncodeMessage(TypeOffer, SDPPayload{
				SDP:  offer.SDP,
				Type: "offer",
			})
			_ = client.Send(offerMsg)
		}
	})

	partRef = room.NewParticipant(
		peerID,
		authResp.UserID,
		authResp.DisplayName,
		authResp.Role,
		*authResp.Permissions,
		false,
		sfuPeer,
		client,
	)

	if err := r.AddParticipant(partRef); err != nil {
		h.sendError(client, "JOIN_REJECTED", err.Error())
		_ = sfuPeer.Close()
		return
	}

	// Configure periodic timer ticks if not already set (sync pulse every 5s, every 1s when <= 60s)
	r.SetTickCallbackOnce(func(remainingSec int) {
		if remainingSec%5 == 0 || remainingSec <= 60 {
			tickMsg, _ := EncodeMessage(TypeSessionTimerTick, SessionTimerTickPayload{
				RemainingSec: remainingSec,
			})
			r.BroadcastAll(tickMsg)
		}
	})

	if partRef.IsInLobby {
		// Participant placed in lobby
		waitingMsg, _ := EncodeMessage(TypeLobbyWaiting, LobbyWaitingPayload{
			Message: "Waiting for a host to admit you into the meeting.",
		})
		_ = client.Send(waitingMsg)

		// Notify hosts and co-hosts
		peerWaitingMsg, _ := EncodeMessage(TypeLobbyPeerWaiting, LobbyPeerWaitingPayload{
			Peer: partRef.Info(),
		})
		r.BroadcastToHosts(peerWaitingMsg)
		return
	}

	activeParts := r.GetParticipants()
	infoList := make([]room.ParticipantInfo, 0, len(activeParts))
	for _, p := range activeParts {
		infoList = append(infoList, p.Info())
	}

	joinedMsg, _ := EncodeMessage(TypeJoined, JoinedPayload{
		PeerID:              peerID,
		UserID:              authResp.UserID,
		DisplayName:         authResp.DisplayName,
		Role:                authResp.Role,
		Permissions:         *authResp.Permissions,
		Policies:            r.Policy(),
		Participants:        infoList,
		SessionRemainingSec: r.RemainingSessionSec(),
		ICEServers:          h.sfuEngine.ICEServers(),
	})
	_ = client.Send(joinedMsg)

	// Broadcast peer_joined to all other participants
	peerJoinedMsg, _ := EncodeMessage(TypePeerJoined, PeerJoinedPayload{
		Peer: partRef.Info(),
	})
	r.Broadcast(peerJoinedMsg, peerID)

	// Subscribe participant to existing published tracks after joined event is dispatched
	r.SubscribeParticipantToExistingTracks(partRef)
}

func (h *Hub) handleOffer(client *Client, payloadBytes []byte) {
	var payload SDPPayload
	if err := json.Unmarshal(payloadBytes, &payload); err != nil {
		h.sendError(client, "INVALID_PAYLOAD", "Invalid SDP offer")
		return
	}

	p := h.getParticipant(client)
	if p == nil || p.Peer == nil {
		h.sendError(client, "NOT_JOINED", "Participant not active in room")
		return
	}

	if err := p.Peer.SetRemoteDescription(webrtc.SessionDescription{
		Type: webrtc.SDPTypeOffer,
		SDP:  payload.SDP,
	}); err != nil {
		h.sendError(client, "SDP_ERROR", fmt.Sprintf("Failed to set remote offer: %v", err))
		return
	}

	answer, err := p.Peer.CreateAnswer()
	if err != nil {
		h.sendError(client, "SDP_ERROR", fmt.Sprintf("Failed to create answer: %v", err))
		return
	}

	ansMsg, _ := EncodeMessage(TypeAnswer, SDPPayload{
		SDP:  answer.SDP,
		Type: "answer",
	})
	_ = client.Send(ansMsg)
}

func (h *Hub) handleAnswer(client *Client, payloadBytes []byte) {
	var payload SDPPayload
	if err := json.Unmarshal(payloadBytes, &payload); err != nil {
		h.sendError(client, "INVALID_PAYLOAD", "Invalid SDP answer")
		return
	}

	p := h.getParticipant(client)
	if p == nil || p.Peer == nil {
		h.sendError(client, "NOT_JOINED", "Participant not active in room")
		return
	}

	_ = p.Peer.SetRemoteDescription(webrtc.SessionDescription{
		Type: webrtc.SDPTypeAnswer,
		SDP:  payload.SDP,
	})

	// Request keyframes from all publishers for subscribed video tracks to ensure instant rendering
	rm, _ := h.getRoomAndParticipant(client)
	if rm != nil {
		for _, pub := range rm.GetParticipants() {
			if pub.ID != p.ID && pub.Peer != nil {
				for _, track := range pub.Peer.PublishedTracks() {
					if track.Kind == webrtc.RTPCodecTypeVideo {
						ssrc := track.SSRC
						pubPeer := pub.Peer
						_ = pubPeer.SendPLI(ssrc)
						time.AfterFunc(150*time.Millisecond, func() {
							_ = pubPeer.SendPLI(ssrc)
						})
						time.AfterFunc(400*time.Millisecond, func() {
							_ = pubPeer.SendPLI(ssrc)
						})
					}
				}
			}
		}
	}
}

func (h *Hub) handleCandidate(client *Client, payloadBytes []byte) {
	var payload CandidatePayload
	if err := json.Unmarshal(payloadBytes, &payload); err != nil {
		return
	}

	p := h.getParticipant(client)
	if p == nil || p.Peer == nil {
		return
	}

	_ = p.Peer.AddICECandidate(webrtc.ICECandidateInit{
		Candidate:        payload.Candidate,
		SDPMid:           payload.SDPMid,
		SDPMLineIndex:    payload.SDPMLineIndex,
		UsernameFragment: payload.UsernameFragment,
	})
}

func (h *Hub) handleChatMessage(client *Client, payloadBytes []byte) {
	var payload ChatMessagePayload
	if err := json.Unmarshal(payloadBytes, &payload); err != nil || payload.Text == "" {
		return
	}

	rm, p := h.getRoomAndParticipant(client)
	if rm == nil || p == nil {
		return
	}

	pInfo := p.Info()
	if !permissions.CanChat(pInfo.Role, rm.Policy(), &pInfo.Permissions) {
		h.sendError(client, "FORBIDDEN", "Chat is disabled by policy")
		return
	}

	broadcastMsg, _ := EncodeMessage(TypeChatMessage, ChatBroadcastPayload{
		ID:          uuid.New().String(),
		PeerID:      client.peerID,
		UserID:      pInfo.UserID,
		DisplayName: pInfo.DisplayName,
		Text:        payload.Text,
		Timestamp:   time.Now(),
	})
	rm.Broadcast(broadcastMsg)
}


func (h *Hub) handleAdmitPeer(client *Client, payloadBytes []byte) {
	var payload AdmitPeerPayload
	if err := json.Unmarshal(payloadBytes, &payload); err != nil || payload.PeerID == "" {
		return
	}

	rm, actor := h.getRoomAndParticipant(client)
	if rm == nil || actor == nil {
		return
	}

	if !permissions.CanModerate(actor.Role, "", permissions.ActionAdmit) {
		h.sendError(client, "FORBIDDEN", "Unauthorized to admit peers")
		return
	}

	admittedP, err := rm.AdmitFromLobby(payload.PeerID)
	if err != nil {
		h.sendError(client, "ADMIT_FAILED", err.Error())
		return
	}

	activeParts := rm.GetParticipants()
	infoList := make([]room.ParticipantInfo, 0, len(activeParts))
	for _, p := range activeParts {
		infoList = append(infoList, p.Info())
	}

	joinedMsg, _ := EncodeMessage(TypeJoined, JoinedPayload{
		PeerID:              admittedP.ID,
		UserID:              admittedP.UserID,
		DisplayName:         admittedP.DisplayName,
		Role:                admittedP.Role,
		Permissions:         admittedP.Permissions,
		Policies:            rm.Policy(),
		Participants:        infoList,
		SessionRemainingSec: rm.RemainingSessionSec(),
		ICEServers:          h.sfuEngine.ICEServers(),
	})
	_ = admittedP.Send(joinedMsg)

	peerJoinedMsg, _ := EncodeMessage(TypePeerJoined, PeerJoinedPayload{
		Peer: admittedP.Info(),
	})
	rm.Broadcast(peerJoinedMsg, admittedP.ID)

	// Subscribe participant to existing published tracks after joined event is dispatched
	rm.SubscribeParticipantToExistingTracks(admittedP)
}

func (h *Hub) handleMutePeer(client *Client, payloadBytes []byte) {
	var payload MutePeerPayload
	if err := json.Unmarshal(payloadBytes, &payload); err != nil || payload.PeerID == "" {
		return
	}

	rm, actor := h.getRoomAndParticipant(client)
	if rm == nil || actor == nil {
		return
	}

	target, ok := rm.GetParticipant(payload.PeerID)
	if !ok {
		return
	}

	if !permissions.CanModerate(actor.Role, target.Role, permissions.ActionMute) {
		h.sendError(client, "FORBIDDEN", "Unauthorized to mute target peer")
		return
	}

	if payload.Media == "audio" {
		target.SetAudioMuted(true)
	} else if payload.Media == "video" {
		target.SetVideoMuted(true)
	}

	muteMsg, _ := EncodeMessage(TypePeerMuted, PeerMutedPayload{
		PeerID:   target.ID,
		Media:    payload.Media,
		ByPeerID: client.peerID,
	})
	rm.Broadcast(muteMsg)
}

